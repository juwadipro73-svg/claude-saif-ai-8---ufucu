#!/usr/bin/env bash
# Step 50 — build the single artifact selected by input.json .kind
# kind apk   -> <name>.apk   (placeholder until the real engine lands; NO credentials inside)
# kind zip   -> <name>-project.zip
# kind video -> <name>-demo.mp4 (ffmpeg synthetic clip; text fallback if ffmpeg absent)
set -euo pipefail
source "$(dirname "$0")/lib.sh"

IN="$SAIF_STATE_DIR/input.json"
KIND=$("$JQ_BIN" -r '.kind' "$IN")
SAFE=$("$JQ_BIN" -r '.prompt // "SaifAIApp"' "$IN" | tr ' ' '_' | tr -cd 'a-zA-Z0-9._-' | cut -c1-48)
[ -n "$SAFE" ] || SAFE="SaifAIApp"
mkdir -p output

case "$KIND" in
  apk)
    ART="output/${SAFE}-${JOB_ID:0:8}.apk"
    printf 'Saif AI Builder placeholder APK — job %s — %s\n' "$JOB_ID" "$SAFE" > "$ART"
    ;;
  zip)
    ART="output/${SAFE}-${JOB_ID:0:8}-project.zip"
    STAGE=$(mktemp -d); mkdir -p "$STAGE/project"
    printf '# %s\n\nGenerated by Saif AI Builder, job %s\n' "$SAFE" "$JOB_ID" > "$STAGE/project/README.md"
    (cd "$STAGE/project" && zip -qr "$OLDPWD/$ART" .)
    rm -rf "$STAGE"
    ;;
  video)
    ART="output/${SAFE}-${JOB_ID:0:8}-demo.mp4"
    if command -v ffmpeg >/dev/null 2>&1; then
      ffmpeg -hide_banner -loglevel error -f lavfi -i "color=size=640x360:duration=3:rate=24:color=black" \
        -vf "drawtext=text='${SAFE}':fontcolor=white:fontsize=36:x=(w-text_w)/2:y=(h-text_h)/2" \
        -pix_fmt yuv420p -y "$ART"
    else
      warn "ffmpeg not available — writing placeholder video file"
      printf 'video placeholder job %s %s\n' "$JOB_ID" "$SAFE" > "$ART"
    fi
    ;;
esac

[ -s "$ART" ] || { err "build produced no artifact"; exit 1; }
{
  echo "artifact_path=$ART"
  echo "artifact_name=$(basename "$ART")"
} >> "$GITHUB_OUTPUT"
echo "artifact ready: $ART ($(stat -c%s "$ART") bytes)"
